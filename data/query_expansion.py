"""
query_expansion.py
질문의 일상어를 약관 용어로 잇는 사전(2026-10-21, rebuild5 준비 4a단계).

검색이 놓치는 문항의 대부분은 낱말 불일치였다 — "해외" ↔ "대한민국 이외의 지역", "앓던 병" ↔ "이미 감염 또는 발병한 질병".
그 문항들은 Dense 후보 20위 밖이라 리랭커까지 가지도 못했다(검색 감사 2026-10-21: R010 R017 R018 R022 R024).
약관 용어를 질문 뒤에 붙이면 BM25가 그 청크를 후보로 올리고 리랭커가 판단한다.

- 트리거는 일상어에만 건다. 이미 약관 용어인 낱말("환급금")에 붙이면 맞던 문항이 밀렸다(4건 3위→4위)
- 확장한 질의는 BM25·리랭커에만 쓴다. Dense에는 원문 — 확장어를 붙이면 Dense 순위가 오히려 떨어졌다(R022 31→71)
- 사전은 평가 정답을 보고 만들면 누설이다. 아래 낱말은 약관 조항 이름·면책 사유 표현에서 골랐고, 평가 세트 220의 숨긴 세트는 보지 않았다
"""

import os
import re

# 사전 판(2026-10-21): v1 = 아래 15개(4a), v2 = data/synonyms.py(질병·약관·일상 + 오타, 4a 15개 포함). 회귀로 v2를 확인하기 전까지 v1
DICT = os.environ.get("PETMINT_EXPAND_DICT", "v1")

# (트리거 — 일상어 정규식, 붙일 약관 용어)
TERMS: list[tuple[str, str]] = [
    (r"해외|외국|여행\s*(?:가서|중에)|일본|미국|괌|중국|태국|유럽|출장", "대한민국 이외의 지역"),
    (r"기왕증|앓던|원래\s*있던\s*병|가입\s*(?:하기\s*)?전부터", "보험계약일 이전에 이미 감염 또는 발병한 질병"),
    (r"한방|한약|침\s*(?:치료|맞)|재활|물리치료", "한의학 침술 대체의료 재활치료"),
    (r"물었|물어서|물림|물렸", "배상책임 타인의 신체의 장해"),
    (r"몇\s*살|살\s*(?:넘|이면|인데|까지)|나이", "가입 연령 생후 60일 만 8세"),
    (r"다른\s*회사|두\s*군데|양쪽|다른\s*데서도|중복\s*(?:가입|보상)", "다른 계약 비례보상 보험금 분담"),
    (r"조건부", "특정 질병 보장제한부 인수"),
    (r"(?:청구|신청)\s*(?:할\s*때|하려면).*(?:서류|뭐)|서류\s*(?:가|는)?\s*뭐|뭐\s*(?:내야|필요)", "진료비 영수증 진료비 세부내역서 진료기록부"),
    (r"입원으로\s*(?:쳐|봐|인정)|맡겨도", "입원의 정의 치료에 전념"),
    (r"밀리|밀려|못\s*냈|안\s*냈|못\s*내서|연체", "납입최고(독촉) 계약의 해지"),
    (r"엉터리|잘못\s*설명|설명을?\s*(?:제대로\s*)?못\s*들", "위법계약의 해지 보험품질보증"),
    (r"영양제|건강\s*식품|보조제", "건강보조 식품 수의사 처방 의약품 이외"),
    (r"맞소송|맞고소|반소", "반소 하나의 소송"),
    (r"장례|화장\s*비", "장례비 사후에 필요한 비용"),
    (r"(?:동물등록\s*)?칩\s*(?:심|이식)", "마이크로 칩 이식 비용"),
]
_COMPILED = {"v1": [(re.compile(p), t) for p, t in TERMS]}


def _compiled(version: str) -> list:
    if version not in _COMPILED:
        assert version == "v2", f"사전 판은 v1·v2: {version}"
        from data.synonyms import ENTRIES
        _COMPILED["v2"] = [(e.trigger, e.expand) for e in ENTRIES]
    return _COMPILED[version]


def expand(query: str, version: str | None = None) -> str | None:
    """걸리는 용어를 질문 뒤에 붙인 문장. 걸리는 것이 없으면 None(원문 그대로 쓴다). version None이면 DICT(기본 v1)"""
    terms = [t for p, t in _compiled(version or DICT) if p.search(query) and t not in query]
    return f"{query} {' '.join(dict.fromkeys(terms))}" if terms else None
