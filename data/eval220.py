# 독립 계산(서빙 코드를 쓰지 않는다)
def day_pay(cost: int, copay: int, pct: int, limit: int) -> int:
    return max(min((cost - copay) * pct // 100, limit), 0)


def lim(grade: str, t: str, scenario: str) -> tuple[int, int, int]:
    """(1일 한도, 보상비율 %, 연간 총 한도) — limit_table 표 값"""
    g = get_limit(grade, t, scenario)
    return g["limit"], round(g["rate"] * 100), g["annual_total"]


def dp_range(total: int, n: int, copay: int, pct: int, limit: int, unit: int = 10_000) -> tuple[int, int]:
    """총액을 n일에 1만원 단위로 나누는 모든 경우(날마다 1만원 이상)의 지급 합계 (최소, 최대) — 날짜별 동적 계획법"""
    T = total // unit
    best = {0: (0, 0)}
    for d in range(n):
        nxt = {}
        for used, (lo, hi) in best.items():
            for x in range(1, T - used - (n - 1 - d) + 1):
                v = day_pay(x * unit, copay, pct, limit)
                k = used + x
                a, b = nxt.get(k, (None, None))
                nxt[k] = (lo + v if a is None else min(a, lo + v), hi + v if b is None else max(b, hi + v))
        best = nxt
    return best[T]


def even_pay(total: int, n: int, copay: int, pct: int, limit: int) -> int:
    """날마다 정확히 total/n원(분수) — 원 미만은 합계에서 한 번 버린다(서빙의 '고르게'와 같은 정의, 계산은 따로)"""
    share = Fraction(total, n)
    v = max(min((share - copay) * pct / 100, limit), 0)
    return math.floor(v * n)


def W(n: int) -> str:
    """판정용 금액 표기 — '42만7000원'(norm 뒤 비교). 만 단위가 딱 떨어지면 '30만원'"""
    man, rest = divmod(n, 10_000)
    if man and rest:
        return f"{man}만{rest}원"
    return f"{man}만원" if man else f"{rest}원"


