def _flat(t: str | None) -> str:
    return re.sub(r"\s+", "", t or "")


def _customers() -> dict[str, dict]:
    cs = json.loads((ROOT / "app" / "fixtures" / "customers.json").read_text(encoding="utf-8"))
    return {p["pet_id"]: dict(p, customer_id=c["customer_id"]) for c in cs for p in c["pets"]}


def _scope(pet: dict) -> SearchScope:
    return SearchScope.for_policies(pet["species"], [{"section_name": x["section_name"], "coverage_type": x.get("coverage_type")}
                                                     for x in pet["policies"]])


def _turns(c: dict) -> list[dict]:
    return c["turns"] if "turns" in c else [c]


def resolve_gold(cases: list[dict], pets: dict, chunks: dict) -> list[str]:
    """정답 근거가 그 반려동물 가입 범위 안 청크에 있는가. 있으면 section·section_name을 청크 값으로 채운다(search_regression.matches 형식)"""
    errors = []
    for c in cases:
        for t in _turns(c):
            pet = pets[t["pet_id"]]
            scope = _scope(pet)
            pool = [x for x in chunks[pet["species"]] if scope.allows(x)]
            any_of = t["id"].startswith("P")          # 원 문항의 gold는 any-of — 범위 안에 하나만 있으면 된다
            kept = []
            for g in t["gold"]:
                name, art, ev = g["section_name"], g["article_num"], _flat(g["evidence"])
                hits = [x for x in pool
                        if (x["section"] == "보통약관" if name is None else (x.get("section_name") == name or (x.get("section_name") or "").endswith(name)))
                        and (art is None or x.get("article_num") == art) and ev in _flat(x["content"])]
                if not hits:
                    if not any_of:
                        errors.append(f"{t['id']}: 근거 없음 — {name} 제{art}조 '{g['evidence']}' ({pet['name']} 범위)")
                    continue
                g["section"], g["section_name"] = hits[0]["section"], hits[0].get("section_name")
                kept.append(g)
            if any_of:
                if not kept:
                    errors.append(f"{t['id']}: 원 문항 gold가 {pet['name']} 범위에 하나도 없다")
                t["gold"] = kept
    return errors


def check_absent(cases: list[dict], pets: dict, chunks: dict) -> list[str]:
    errors = []
    for c in cases:
        pet = pets[c["pet_id"]]
        scope = _scope(pet)
        text = "".join(_flat(x["content"]) for x in chunks[pet["species"]] if scope.allows(x))
        errors += [f"{c['id']}: 약관에 있음 — '{w}'" for w in c.get("absent", []) if _flat(w) in text]
    return errors


def check_customers(cases: list[dict], pets: dict) -> list[str]:
    errors = []
    for pid, (cust, name, sp) in PETS.items():
        p = pets.get(pid)
        if p is None or (p["customer_id"], p["name"], p["species"]) != (cust, name, sp):
            errors.append(f"원장 반려동물 불일치: {pid}")
    for pid, d in FACTS["contract"].items():
        dates = {x["contract_date"] for x in pets[pid]["policies"] if x.get("coverage_type")}
        if dates != {d}:
            errors.append(f"가입일 불일치 {pid}: {dates} != {d}")
    for pid, age in FACTS["age"].items():
        if pets[pid].get("age") != age:
            errors.append(f"나이 불일치 {pid}: {pets[pid].get('age')} != {age}")
    claims = json.loads((ROOT / "db" / "fixtures" / "claims.json").read_text(encoding="utf-8"))
    for (pid, kind), used in FACTS["used"].items():
        got = sum(x["paid"] for x in claims if x["pet_id"] == pid and x["treatment_type"] == kind and x["treatment_date"] <= ON.isoformat())
        if got != used:
            errors.append(f"청구 이력 불일치 {pid} {kind}: {got} != {used}")
    for pid, n in FACTS["mri"].items():
        got = sum(1 for x in claims if x["pet_id"] == pid and x["mri"])
        if got != n:
            errors.append(f"MRI 이력 불일치 {pid}: {got} != {n}")
    by_id = {t["id"]: t for c in cases for t in _turns(c)}
    for cid, word in NOT_ENROLLED_CHECK.items():
        pet = pets[by_id[cid]["pet_id"]]
        if any(word in x["section_name"] for x in pet["policies"]):
            errors.append(f"{cid}: 미가입이라 했는데 {pet['name']}에 '{word}' 특약이 있다")
    for c in cases:
        for t in _turns(c):
            pet = pets[t["pet_id"]]
            excl = {e for x in pet["policies"] for e in x.get("excluded_conditions") or []}
            for b in t["expect"].get("banner") or []:
                if b not in excl:
                    errors.append(f"{t['id']}: 배너 {b} — {pet['name']}의 부담보가 아니다")
            for k, v in t["expect"]["calc_values"].items():
                if k.endswith("section_name") and v not in {x["section_name"] for x in pet["policies"]}:
                    errors.append(f"{t['id']}: {v} — {pet['name']}의 가입 특약이 아니다")
    return errors


def hidden_ids(cases: list[dict]) -> set[str]:
    """축마다 정렬한 id의 5개 중 3번째 — 20%"""
    out = set()
    for axis in "SPCMNL":
        ids = sorted(c["id"] for c in cases if c["id"].startswith(axis))
        out.update(i for k, i in enumerate(ids) if k % 5 == 2)
    return out


def build() -> tuple[list[dict], list[str]]:
    cases = S_cases() + P_cases() + C_cases() + M_cases() + N_cases() + L_cases()
    for c in cases:
        c["axis"] = c["id"][0]
        for t in _turns(c):
            pid = t["pet_id"]
            t["customer_id"], t["species"] = PETS[pid][0], PETS[pid][2]
            t["answer"] = t.get("answer") or REF_ANSWERS.get(t["id"], "")
            # 범위·고르게는 1만원 단위 DP로 낸 값 — 서빙은 분수로 정확히 낸다. 원 단위 차이를 1,000원까지 허용
            t["expect"]["calc_tol"] = {k: 1_000 for k in t["expect"]["calc_values"] if k in ("range_min", "range_max", "even")}
    pets = _customers()
    chunks = {sp: json.loads((ROOT / "data" / "chunks" / f"petmint_{sp}.json").read_text(encoding="utf-8")) for sp in ("강아지", "고양이")}
    errors = resolve_gold(cases, pets, chunks) + check_absent(cases, pets, chunks) + check_customers(cases, pets)
    ids = [c["id"] for c in cases]
    if len(ids) != len(set(ids)):
        errors.append("id 중복")
    return cases, errors


def main() -> None:
    cases, errors = build()
    counts = {a: sum(1 for c in cases if c["axis"] == a) for a in "SPCMNL"}
    print("문항", len(cases), counts, "| 멀티턴 턴", sum(len(c["turns"]) for c in cases if "turns" in c))
    if errors:
        print(f"검수 실패 {len(errors)}건 — 쓰지 않는다")
        for e in errors:
            print("  ", e)
        raise SystemExit(1)
    hid = hidden_ids(cases)
    visible = [c for c in cases if c["id"] not in hid]
    hidden = [c for c in cases if c["id"] in hid]
    meta = dict(created=ON.isoformat(), base_date=ON.isoformat(), source="data/eval220.py")
    (OUT / "eval220.json").write_text(json.dumps(dict(meta, cases=visible), ensure_ascii=False, indent=1), encoding="utf-8")
