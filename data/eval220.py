def to_species(name: str, sp: str) -> str:
    """원 문항이 강아지인데 고양이에게 물으면 같은 조항의 고양이 이름으로"""
    if sp == "고양이":
        return name.replace("반려견", "반려묘").replace("펫퍼민트 기부", "펫퍼민트 Cat 기부").replace("(반려견)", "(반려묘)")
    return name


