def check(texts: list[str]) -> list[str]:
    """사전 검사 — expand 낱말이 약관 글에 하나도 없거나, 트리거가 약관 말 자체에 걸리면 문제 목록"""
    flat = re.sub(r"\s+", "", "\n".join(texts))
    out = []
    for e in ENTRIES:
        words = [w for w in re.split(r"\s+", e.expand) if len(w) >= 2]
        missing = [w for w in words if re.sub(r"[()]", "", w) not in flat and w not in flat]
        if len(missing) == len(words):
            out.append(f"expand 낱말이 약관에 없음: {e.expand}")
        for p in e.policy:
            if e.trigger.search(p):
                out.append(f"트리거가 약관 말에 걸림: {e.words[:2]} ↔ {p}")
    return out


def exclusion_aliases() -> dict[str, tuple[str, ...]]:
    """부담보 배너 동의어 — exclusion 키 → 고객 말(정규식 조각이 아닌 글자 그대로만: 공백·메타문자 없는 것)"""
    out: dict[str, tuple[str, ...]] = {}
    for e in ENTRIES:
        if e.exclusion:
            plain = [w for w in (*e.words, *e.typos, *e.say, *e.policy) if re.fullmatch(r"[가-힣A-Za-z]+", w.replace(" ", ""))]
            out[e.exclusion] = tuple(dict.fromkeys(w.replace(" ", "") for w in plain))
    return out


def rewrite_hints(question: str) -> list[tuple[str, tuple[str, ...]]]:
    """학습 질문 재작성 힌트 — 질문에 든 약관 말과 그 고객 말(say). say 없는 항목은 힌트 없음"""
    return [(p, e.say) for e in ENTRIES if e.say for p in e.policy if p in question]


def stats() -> dict:
    from collections import Counter
    c = Counter(e.kind for e in ENTRIES)
    return {"entries": len(ENTRIES), **c, "typo_words": sum(len(e.typos) for e in ENTRIES),
            "trigger_words": sum(len(e.words) + len(e.typos) for e in ENTRIES),
            "with_rewrite_hint": sum(1 for e in ENTRIES if e.say and e.policy)}
