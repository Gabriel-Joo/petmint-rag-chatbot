def cert_allowance(eid: str, month: str) -> int:
    """그 달의 자격수당 — 사본 제출 다음 달부터, 둘 이상이면 큰 것 하나(제27조)"""
    paid = [CERT_PAY[c] for e, c, _, sub in CERTS if e == eid and sub and sub[:7] < month[:7]]
    return max(paid, default=0)


def probation_end(hire: str) -> str:
    """수습이 끝난 뒤 첫 급여 달(YYYY-MM-01) — 입사일부터 3개월(제7조 ①). 입사 달 포함 3개 달을 90%로 친다"""
    y, m = int(hire[:4]), int(hire[5:7]) + 3
    y, m = y + (m - 1) // 12, (m - 1) % 12 + 1
    return f"{y}-{m:02d}-01"


def payroll(p) -> list[dict]:
    eid, _, _, grade, _, etype, hire, _, _, retired, extra = p
    out = []
    for m in MONTHS:
        if hire[:7] > m[:7] or (retired and retired[:7] < m[:7]):
            continue
        base = BASE[grade] + extra
        if etype == "계약직":
            base = 2_800_000
        probation = etype == "정규직" and not p[7] and m < probation_end(hire)
        if probation:
            base = int(base * 0.9)
        fixed = MEAL + TRANSIT + cert_allowance(eid, m)
        overtime = OVERTIME.get(eid, 0) if not probation else 0
        bonus = base // 2 if m == BONUS_MONTH and etype == "정규직" else 0
        out.append(dict(employee_id=eid, pay_month=m, base_pay=base, fixed_allowances=fixed, overtime_pay=overtime,
                        bonus=bonus, ordinary_wage=base + fixed))
    return out


